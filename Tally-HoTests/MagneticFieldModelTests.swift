//  WMM2025 against NOAA's published test values (#21).
//
//  The table below is NOAA's WMM2025_TEST_VALUES.txt, all 100 points, columns unchanged:
//  decimal year, height above the WGS-84 ellipsoid (km), geodetic latitude and longitude (deg),
//  declination D and inclination I (deg), then H, X, Y, Z and F (nT). D and I are published to
//  0.01°, so that is their tolerance; the intensities are published to 1e-6 nT, and the model here
//  must reproduce them to 0.1 nT — a thousandth of the field-check threshold's precision needs.
//

import Testing
import Foundation
@testable import Tally_Ho

struct MagneticFieldModelTests {

    private struct TestPoint {
        var year, altitudeKm, latitude, longitude: Double
        var declination, inclination, h, x, y, z, f: Double
    }

    private var points: [TestPoint] {
        Self.noaaTestValues
            .split(separator: "\n")
            .map { line in line.split(separator: " ").compactMap { Double($0) } }
            .filter { $0.count == 11 }
            .map { v in
                TestPoint(year: v[0], altitudeKm: v[1], latitude: v[2], longitude: v[3],
                          declination: v[4], inclination: v[5], h: v[6], x: v[7], y: v[8],
                          z: v[9], f: v[10])
            }
    }

    private func field(_ p: TestPoint) -> MagneticFieldModel.Field {
        MagneticFieldModel.field(latitudeDeg: p.latitude, longitudeDeg: p.longitude,
                                 altitudeKm: p.altitudeKm, decimalYear: p.year)
    }

    /// Signed difference of two angles, folded into ±180.
    private func angleError(_ a: Double, _ b: Double) -> Double {
        var d = (a - b).truncatingRemainder(dividingBy: 360)
        if d > 180 { d -= 360 }
        if d < -180 { d += 360 }
        return abs(d)
    }

    @Test func allHundredNOAATestPointsAreParsed() {
        #expect(points.count == 100)
    }

    @Test func totalIntensityMatchesNOAA() {
        for p in points {
            let error = abs(field(p).totalNT - p.f)
            #expect(error < 0.1, "F at \(p.latitude), \(p.longitude), \(p.altitudeKm) km, \(p.year)")
        }
    }

    @Test func inclinationMatchesNOAA() {
        for p in points {
            let error = abs(field(p).inclinationDeg - p.inclination)
            #expect(error <= 0.01, "I at \(p.latitude), \(p.longitude), \(p.altitudeKm) km, \(p.year)")
        }
    }

    @Test func declinationMatchesNOAA() {
        for p in points {
            let error = angleError(field(p).declinationDeg, p.declination)
            #expect(error <= 0.01, "D at \(p.latitude), \(p.longitude), \(p.altitudeKm) km, \(p.year)")
        }
    }

    @Test func componentsMatchNOAA() {
        for p in points {
            let computed = field(p)
            #expect(abs(computed.northNT - p.x) < 0.1)
            #expect(abs(computed.eastNT - p.y) < 0.1)
            #expect(abs(computed.downNT - p.z) < 0.1)
            #expect(abs(computed.horizontalNT - p.h) < 0.1)
        }
    }

    // MARK: - Where it matters

    @Test func gevsBalconyMatchesTheDeclinationIOSReported() {
        // Log 849c560a: 40.748°N 74.037°W, near sea level, 2026-10-09. iOS logged −12.46°.
        let date = ISO8601DateFormatter().date(from: "2026-10-09T21:23:00Z")!
        let here = MagneticFieldModel.field(latitudeDeg: 40.7483, longitudeDeg: -74.0367,
                                            altitudeKm: 0, date: date)
        #expect(abs(here.declinationDeg - (-12.46)) < 0.05)
        // What the field check expects there: about 50.8 µT, dipping about 65.6°.
        #expect(abs(here.totalUT - 50.78) < 0.05)
        #expect(abs(here.inclinationDeg - 65.56) < 0.05)
    }

    @Test func decimalYearIsUTCFractionOfTheYear() {
        let formatter = ISO8601DateFormatter()
        #expect(MagneticFieldModel.decimalYear(from: formatter.date(from: "2025-01-01T00:00:00Z")!) == 2025.0)
        // 2026 has 365 days; noon on 2 July is day 182.5 from the start.
        let midYear = MagneticFieldModel.decimalYear(from: formatter.date(from: "2026-07-02T12:00:00Z")!)
        #expect(abs(midYear - (2026 + 182.5 / 365)) < 1e-9)
    }

    @Test func validityIsTheModelsFiveYears() {
        #expect(MagneticFieldModel.isValid(decimalYear: 2025.0))
        #expect(MagneticFieldModel.isValid(decimalYear: 2029.99))
        #expect(!MagneticFieldModel.isValid(decimalYear: 2024.99))
        #expect(!MagneticFieldModel.isValid(decimalYear: 2030.01))
    }

